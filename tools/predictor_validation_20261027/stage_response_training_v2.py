"""Reviewed training channels with clock-aligned causal host covariate paths.

This fixes the legacy path's BEGIN-notice origin. Stream elapsed is deliberately
not fitted against a host interval. No future event becomes a runtime feature.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import stage_response_features_v1 as old
from .stage_host_partition_v1 import extract as partition, require

SCHEMA = 'gsdeploy.reviewed_stage_response_training.v2'


def causal_path(events, start, end, owner, phase):
    require(old.stamp(start) and old.stamp(end) and start <= end,
        'Integer host interval required')
    changes = sorted({start, *[e['collector_processing_time_ns'] for e in events
        if start < e['collector_processing_time_ns'] < end]})
    rows = []
    for index, cutoff in enumerate(changes):
        stop = changes[index+1] if index+1 < len(changes) else end
        if stop == cutoff:
            continue
        state = old.visible_prefix(events, cutoff, owner, phase)
        rows.append(dict(left_ns=cutoff, right_ns=stop, duration_ns=stop-cutoff,
            state=state, each_state_uses_only_its_processed_prefix=True))
    require(sum(x['duration_ns'] for x in rows) == end-start,
        'Covariate exposure must exactly cover its response clock')
    return rows


def extract(training_review):
    # This checks every unchanged source and the complete training role before
    # inspecting response labels. v1's permissive raw-only entry is not used.
    host = partition(training_review)
    report_ref = old.receipt(training_review)
    report = old.checked(report_ref)
    raw_ref = report['inputs']['raw.json']
    raw = old.checked(raw_ref)
    plan, _, jobs = old.training_roles(raw)
    legacy = old.extract(raw_ref['path'])
    events_by_job = {jid: old.ordered_events([r for r in raw['request_records']
        if r['profile_job_id'] == jid]) for jid in jobs}
    stages = []
    for original in legacy['stages']:
        stage = dict(original)
        stage['legacy_post_BEGIN_notice_path'] = stage.pop('processed_covariate_path')
        stage.pop('training_only_design_exposures')
        label = stage['response_labels']
        start, end = label['host_observed_interval_ns']
        events = events_by_job[stage['job_id']]
        stage['full_host_wall_covariate_path'] = causal_path(events, start, end,
            stage['owner'], stage['semantic_phase'])
        notice = stage['BEGIN_available_ns']
        stage['elapsed_host_wall_at_BEGIN_notice_ns'] = min(notice, end)-start
        stage['full_host_label_clock_origin_ns'] = start
        stage['shape_available_to_parent_before_BEGIN_notice'] = False
        stage['prior_shape_template_qualification_required_for_prospective_use'] = True
        stage['stream_elapsed_covariate_path'] = None
        stage['stream_response_fit_eligible'] = False
        stage['stream_unavailable_reason'] = (
            'No exact stream-start/end wall interval or all-stream service clock; '
            'host END cannot bound elapsed-stream exposure. Native API numeric authentication unresolved.')
        stage['host_channel_is_effective_SM_service'] = False
        stage['host_training_fit_diagnostic_eligible'] = stage['stage_kind'] == 'language_forward'
        stages.append(stage)
    sources = [report_ref, *legacy['sources'], old.receipt(__file__),
        old.receipt(Path(__file__).with_name('stage_host_partition_v1.py'))]
    require(all(old.receipt(r['path']) == r for r in sources), 'Source changed during extraction')
    return dict(schema=SCHEMA, status='REVIEWED_CLOCK_ALIGNED_TRAINING_DIAGNOSTICS_ONLY',
        mode=plan['mode'], sources=sources, stages=stages, host_partition=host,
        fixed_contract=old.CONTRACT, full_host_exposures_reconstruct_labels=True,
        priming_rows_excluded=legacy['priming_rows_excluded'], fit_performed=False,
        model_selected=False, main_queue_provider_eligible=False,
        GPU_started=False, validation_labels_read=False, final_gain_eligible=False,
        limitations=['Observed future covariate path is a training likelihood input, never an evaluation replay.',
            'Runtime future peer/notification events must be generated by a composable joint simulator.',
            'Host wall and stream response are separate channels; only host wall gets a clock-aligned path.',
            'One capture cannot establish independent precision or select a generalizing model.',
            'Exact host decomposition does not yet supply conditional sync/host-gap distributions.'])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--training-review', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    result = extract(args.training_review)
    with Path(args.output).open('x') as stream:
        json.dump(result, stream, ensure_ascii=False, indent=2, allow_nan=False)
        stream.write('\n')
    print(json.dumps(dict(status=result['status'], stages=len(result['stages']))))
