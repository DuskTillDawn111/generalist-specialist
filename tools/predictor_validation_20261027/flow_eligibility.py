"""Source-bound original rho and native stability evidence for flow diagnostics.

This independent addendum never changes frozen predictions, outcomes or scoring.
The original catalog planning rule is distinct from retrospective busy ratios
and from finite-trace forecast load. Missing execution/resource applicability
remains UNKNOWN. This addendum alone cannot authorize a final gain claim.
"""
from __future__ import annotations
import argparse
import collections
import copy
import json
import math
from pathlib import Path
from types import SimpleNamespace
import time

from gsdeploy.performance import resolve_service
from gsdeploy.routing import Router
from gsdeploy.stability import reconstruct, classify, DEFAULT_THRESHOLDS
from .profiling import digest
from .probe_validation import read, receipt, save

RHO_MAX = .8
RHO_TOLERANCE = 1e-8
BINDING_SCHEMA = 'gsdeploy.native_flow_catalog_capacity_binding.v1'


def _verify(ref):
    if not isinstance(ref,dict) or receipt(ref['path'])!=ref:
        raise ValueError('Changed or missing eligibility source receipt')


def _number(v,positive=False):
    return type(v) in (int,float) and math.isfinite(v) and (v>0 if positive else v>=0)


def _routing(plan,candidate):
    """Original model-family offered rps; explicit routing weights required."""
    aliases=plan['aliases'];rates=plan['workload_rps'];weights=candidate.get('routing_weights')
    if not isinstance(weights,dict) or set(weights)!=set(rates):
        raise ValueError('Explicit planning routing_weights required; actual counts cannot replace offered rates')
    by_family={t:{} for t in rates}
    for task,offered in rates.items():
        row=weights[task]
        if not _number(offered,True) or not row or any(not _number(v) for v in row.values()) or not math.isclose(sum(row.values()),1.,rel_tol=1e-7,abs_tol=1e-9):
            raise ValueError('Normalized planning route weights and positive offered rates required')
        for alias,weight in row.items():
            if alias not in aliases or task not in aliases[alias]['supported_tasks']:
                raise ValueError('Unsupported planning alias/task route')
            family=aliases[alias]['family']
            by_family[task][family]=by_family[task].get(family,0.)+offered*weight
    # The declared finite route sequence must be generated by these weights.
    # Family-average admission retains its historical treatment of uneven
    # same-family aliases; this check does not invent a new alias rho limit.
    router=Router(weights)
    if set(candidate['routes'])!={r['request_id'] for r in plan['trace']}:
        raise ValueError('Complete declared routes required')
    for row in plan['trace']:
        if router.choose(row['task'])!=candidate['routes'][row['request_id']]:
            raise ValueError('Static candidate routes do not match planning routing_weights')
    return by_family


def _binding(plan,candidate,catalog):
    """Check explicit new-context provenance; legacy catalogs stay unbound.

    This verifies a declared planning service contract, not physical stationarity
    or calibrated uncertainty. Independent service validation is separate.
    """
    b=catalog.get('native_flow_capacity_binding')
    if not isinstance(b,dict):return False,'MISSING_CURRENT_EXECUTION_RESOURCE_CAPACITY_BINDING'
    if (b.get('schema')!=BINDING_SCHEMA or b.get('execution_context_sha256')!=candidate['execution_context_sha256']
            or b.get('resource_configuration_sha256')!=digest(candidate.get('resource_configuration'))
            or b.get('split')!='training' or not b.get('source_receipts')):
        return False,'CAPACITY_BINDING_CONTEXT_RESOURCE_OR_TRAINING_MISMATCH'
    native_training=False
    for ref in b['source_receipts']:
        _verify(ref)
        if Path(ref['path']).suffix=='.json':
            source=read(ref['path'])
            if source.get('kind')=='measured' and source.get('backend')=='native':
                if (source.get('execution_context_sha256')!=candidate['execution_context_sha256']
                        or source.get('status')!='completed'
                        or source.get('resource_configuration')!=candidate.get('resource_configuration')
                        or any(source.get(k) for k in ('errors','runtime_errors','telemetry_errors'))
                        or not source.get('request_records')
                        or any(r.get('split')!='training' or r.get('status')!='completed' for r in source['request_records'])):
                    return False,'CAPACITY_BINDING_NATIVE_TRAINING_IDENTITY_MISMATCH'
                native_training=True
    if not native_training:return False,'CAPACITY_BINDING_HAS_NO_MATCHING_NATIVE_TRAINING_OBSERVATIONS'
    return True,'SOURCE_BOUND_TRAINING_PLANNING_CONTRACT_NOT_A_PHYSICAL_CAPACITY_BOUND'


def original_rho(plan,candidate,catalog):
    """Reproduce the original family rho formula from planned rates/resolver.

    ``rho_threshold_satisfied`` is arithmetic under the supplied catalog.
    ``rho_admission_passed`` additionally requires explicit catalog applicability
    to this base execution identity and resource configuration; never defaults
    to True. No native outcomes are an input to this function.
    """
    try:
        routing=_routing(plan,candidate)
        deployment=dict(collections.Counter(v['family'] for v in plan['aliases'].values()))
        for family,count in deployment.items():
            if family not in catalog['models'] or str(count) not in catalog['capacity_factors'][family]:
                raise ValueError('Unmeasured original catalog deployment count')
        service,evidence=resolve_service(catalog,deployment,routing,plan['workload_rps'],plan['window_seconds'],
            plan.get('seed',42),plan.get('arrival_process','deterministic_periodic'))
        bound,reason=_binding(plan,candidate,catalog)
        if service is None:
            return {'status':'UNKNOWN','rho_by_family':None,'rho_threshold_satisfied':None,
                'rho_admission_passed':None,'catalog_applicable':bound,'applicability_reason':reason,
                'performance_evidence':evidence,'reason':'ORIGINAL_RESOLVER_HAS_NO_SERVICE_EVIDENCE'}
        demand={m:0. for m in deployment}
        for task,row in routing.items():
            for family,rate in row.items():
                if rate:
                    value=service.get(family,{}).get(task)
                    if not _number(value,True):raise ValueError('Missing finite original resolver route service')
                    demand[family]+=rate*value/1000
        capacity={m:catalog['capacity_factors'][m][str(n)] for m,n in deployment.items()}
        if any(not _number(v,True) for v in capacity.values()):raise ValueError('Positive original catalog capacity factors required')
        rho={m:demand[m]/capacity[m] for m in deployment}
        passed=max(rho.values())<=RHO_MAX+RHO_TOLERANCE
        return {'status':'ASSESSED' if bound else 'DIAGNOSTIC_UNBOUND','rho_by_family':rho,'max_rho':max(rho.values()),
            'rho_threshold_satisfied':passed,'rho_admission_passed':passed if bound else None,
            'catalog_applicable':bound,'applicability_reason':reason,'routing_rps_by_family':routing,
            'deployment_by_family':deployment,'service_time_ms':service,'capacity_factors':capacity,
            'performance_evidence':evidence,'threshold':RHO_MAX,'tolerance':RHO_TOLERANCE,
            'formula':'rho_m = sum_t planned_routing_rps[t,m] * original_resolve_service_ms[m,t] /1000 / original_capacity_factor[m,n_m]',
            'scope':'Original catalog family-average planning rule; no actual busy ratio, finite-count/H rate, observed service, or new per-alias threshold'}
    except (KeyError,ValueError,TypeError) as exc:
        return {'status':'UNKNOWN','rho_by_family':None,'rho_threshold_satisfied':None,'rho_admission_passed':None,
            'reason':type(exc).__name__+':'+str(exc)}


def seal(plan_path,output):
    output=Path(output).resolve()
    if output.exists():raise FileExistsError(output)
    plan=read(plan_path)
    if plan.get('schema')!='gsdeploy.native_flow_plan.v1':raise ValueError('Native flow plan required')
    if 'plan_sha256' in plan and digest({k:v for k,v in plan.items() if k!='plan_sha256'})!=plan['plan_sha256']:
        raise ValueError('Flow plan self hash mismatch')
    _verify(plan['catalog']);catalog=read(plan['catalog']['path'])
    sources=[receipt(plan_path),plan['catalog'],receipt(__file__)]
    import gsdeploy.stability,gsdeploy.performance,gsdeploy.config,gsdeploy.routing
    sources.extend(receipt(m.__file__) for m in (gsdeploy.stability,gsdeploy.performance,gsdeploy.config,gsdeploy.routing))
    for key in ('runner_source','context','profile_plan'):
        if key in plan:_verify(plan[key]);sources.append(plan[key])
    binding=catalog.get('native_flow_capacity_binding',{})
    sources.extend(binding.get('source_receipts',[]))
    for ref in sources:_verify(ref)
    before=time.perf_counter_ns()
    rows=[{'candidate_id':c['id'],'original_rho':original_rho(plan,c,catalog)} for c in plan['candidates']]
    value={'schema':'gsdeploy.sealed_native_flow_eligibility.v1','created_ns':time.perf_counter_ns(),
        'information_cutoff_ns':before,'plan':receipt(plan_path),'catalog':plan['catalog'],'source_receipts':sources,
        'thresholds':copy.deepcopy(DEFAULT_THRESHOLDS),'candidates':rows,'GPU_started':False,
        'qualification_policy':'Original rho threshold plus explicit current-context/resource planning evidence; missing stays UNKNOWN',
        'final_gain_eligible':False,'final_gain_scope':'This addendum only establishes capacity/stability components; quality/memory/energy/cohort/executor/final paired protocol require separate verification'}
    save(output,value);return value


def native_stability(plan,candidate,raw,catalog,thresholds=None):
    """Adapt flow times to original reconstruct/classify without inferred submits."""
    thresholds=copy.deepcopy(DEFAULT_THRESHOLDS if thresholds is None else thresholds)
    if thresholds!=DEFAULT_THRESHOLDS:raise ValueError('Original stability thresholds must remain unchanged')
    if (raw.get('schema')!='gsdeploy.native_flow_collection.v1' or raw.get('kind')!='measured'
            or raw.get('backend')!='native' or raw.get('candidate_id')!=candidate['id']
            or raw.get('execution_context_sha256')!=candidate['execution_context_sha256']):
        raise ValueError('Matching actual native flow identity required')
    if raw.get('trace_sha256',raw.get('cohort_sha256'))!=digest(plan['trace']):raise ValueError('Actual offered trace identity mismatch')
    start,end,stop=raw['phase_start_ns'],raw['deadline_ns'],raw['observation_end_ns']
    if end-start!=round(plan['window_seconds']*1e9):raise ValueError('Actual measurement duration differs from plan')
    records=raw['request_records'];actual={r['request_id']:r for r in records}
    if len(actual)!=len(records) or set(actual)!={r['request_id'] for r in plan['trace']}:raise ValueError('Actual offered cohort incomplete or foreign')
    for row in plan['trace']:
        r=actual[row['request_id']]
        if (r['task'],r['pool_id'],r['model'],r['scheduled_time_ns'])!=(row['task'],row['pool_id'],candidate['routes'][row['request_id']],start+row['offset_ns']):
            raise ValueError('Actual route/input/scheduled arrival mismatch')
    adapter=copy.deepcopy(raw)
    adapter['measurement_window']={'start_time_ns':start,'end_time_ns':end,'drain_end_time_ns':stop,
        'drain_seconds':(stop-end)/1e9,'duration_seconds':plan['window_seconds']}
    adapter['drain_timeout_seconds']=plan['drain_seconds']
    adapter['errors']=[*raw.get('errors',[]),*raw.get('runtime_errors',[]),*raw.get('telemetry_errors',[])]
    standalone={alias:SimpleNamespace(service_time_ms=catalog['models'][spec['family']]['service_time_ms']) for alias,spec in plan['aliases'].items()}
    evidence=reconstruct(adapter,standalone,thresholds);result=classify(evidence,thresholds)
    # Existing reconstruct accepts a missing shutdown map as no failures. The
    # addendum requires actual shutdown evidence for every declared worker.
    shutdown=raw.get('shutdown')
    shutdown_complete=isinstance(shutdown,dict) and set(shutdown)==set(plan['aliases'])
    qualified=(result['stability_state_v2'] in {'steady','recoverable_congested'} and shutdown_complete
        and len(records)>0 and all(r['status']=='completed' for r in records)
        and not raw.get('qualification_issues') and raw.get('collection_complete') is True)
    return {'status':'ASSESSED','stability':result,'stability_evidence':evidence,
        'original_stability_passed':qualified,'shutdown_coverage_complete':shutdown_complete,
        'scope':'Original actual host send-start backlog, original standalone service-demand weights, original thresholds and bounded parent receipt recovery',
        'qualification_reasons':([] if qualified else ['ORIGINAL_STABILITY_OR_COMPLETE_NATIVE_PROTOCOL_NOT_ESTABLISHED'])}


def report(sealed_path,raw_paths,output):
    output=Path(output).resolve()
    if output.exists():raise FileExistsError(output)
    sealed=read(sealed_path)
    if sealed.get('schema')!='gsdeploy.sealed_native_flow_eligibility.v1':raise ValueError('Prospective eligibility seal required')
    for ref in sealed['source_receipts']:_verify(ref)
    plan=read(sealed['plan']['path']);catalog=read(sealed['catalog']['path'])
    by_id={c['id']:c for c in plan['candidates']};planning={c['candidate_id']:c['original_rho'] for c in sealed['candidates']}
    seen=set();rows=[]
    for path in raw_paths:
        raw=read(path);cid=raw['candidate_id']
        if cid not in by_id or cid in seen:raise ValueError('Duplicate or foreign raw candidate')
        seen.add(cid)
        if raw.get('plan')!=sealed['plan']:raise ValueError('Actual raw plan differs from eligibility seal')
        if raw.get('resource_configuration')!=by_id[cid].get('resource_configuration'):raise ValueError('Actual raw resource configuration differs from plan')
        if raw.get('phase_start_ns',0)<=sealed['created_ns']:raise ValueError('Planning eligibility must be sealed before actual measurement')
        observed=native_stability(plan,by_id[cid],raw,catalog,sealed['thresholds'])
        capacity=planning[cid]['rho_admission_passed']
        joint=capacity and observed['original_stability_passed'] if capacity is not None else None
        rows.append({'candidate_id':cid,'raw_source':receipt(path),'original_rho':planning[cid],**observed,
            'original_capacity_and_stability_passed':joint,'final_gain_eligible':False})
    for cid in sorted(set(by_id)-seen):rows.append({'candidate_id':cid,'status':'NOT_RUN','original_rho':planning[cid],
        'original_capacity_and_stability_passed':None,'final_gain_eligible':False})
    value={'schema':'gsdeploy.native_flow_eligibility_addendum.v1','status':'ASSESSED' if len(seen)==len(by_id) else 'INCOMPLETE',
        'sealed_source':receipt(sealed_path),'report_source':receipt(__file__),'candidates':rows,'GPU_started':False,
        'thresholds':sealed['thresholds'],'final_gain_eligible':False,
        'scope':'Independent source-bound original capacity/stability components; diagnostic rankings remain valid to assess without a final gain qualification claim'}
    save(output,value);return value


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__);sub=parser.add_subparsers(dest='op',required=True)
    p=sub.add_parser('seal');p.add_argument('--plan',required=True);p.add_argument('--output',required=True)
    p=sub.add_parser('report');p.add_argument('--sealed',required=True);p.add_argument('--raw',required=True,action='append');p.add_argument('--output',required=True)
    a=parser.parse_args(argv);v=seal(a.plan,a.output) if a.op=='seal' else report(a.sealed,a.raw,a.output)
    print(json.dumps({'status':v.get('status','SEALED'),'output':str(Path(a.output).resolve()),'GPU_started':False}));return 0

if __name__=='__main__':raise SystemExit(main())
