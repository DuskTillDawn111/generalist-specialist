"""Training-only joint request residual vectors in learned response coordinates.

An empirical vector is selected by exact PUBLIC owner/task/input identity,
equal capture weighting, then a within-capture draw. All entry/forward/OCR/tail
nodes, internal marks and their paired three-leg notice lags move together.
Future peer paths are generated by the CPU reference, never copied from donors.
The transport and residual sharing assumptions are not prospective qualification.
"""
