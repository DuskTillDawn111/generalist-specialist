SCHEMA='gsdeploy.joint_request_response_transport_training_candidate.v2'
RATE_DENOMINATOR=1_000_000


def require(value,message):
    if not value:raise ValueError(message)


def fraction_record(x):
    x=Fraction(x);return dict(numerator=x.numerator,denominator=x.denominator)


def fraction_read(x):
    require(type(x) is dict and set(x)=={'numerator','denominator'}
        and type(x['numerator']) is int and x['numerator']>=0
        and type(x['denominator']) is int and x['denominator']>0,'Exact nonnegative rational record required')
    return Fraction(x['numerator'],x['denominator'])


def checked_lags(values):
    require(type(values) is dict and set(values)=={'reader_delay_ns','dequeue_extra_ns','processing_extra_ns'}
        and all(type(x) is int and x>=0 for x in values.values()),
        'Exactly three nonnegative integer notification lag legs required')
    return values


def lags(occurrence,reader,dequeue,processing):
    values=[occurrence,reader,dequeue,processing]
    require(all(type(x) is int and x>=0 for x in values) and values==sorted(values),
        'Four explicit monotone source clocks required; no missing delay is zero')
    return dict(reader_delay_ns=reader-occurrence,dequeue_extra_ns=dequeue-reader,
        processing_extra_ns=processing-dequeue)


def response_rate(state,beta):
    value=math.exp(-sum(state[k]*b for k,b in zip(
        ('peer_visible_macro_owner_count','peer_same_visible_macro_phase_owner_count'),beta)))
    # Explicit fixed numerical approximation; not native integer-clock evidence.
    return Fraction(max(1,round(value*RATE_DENOMINATOR)),RATE_DENOMINATOR)


def progress(macro,at,beta):
    require(macro['left_ns']<=at<=macro['right_ns'],'Mark must belong to its OCCURRENCE macro')
    result=Fraction(0)
    for piece in macro['causal_covariate_path']:
        span=max(0,min(at,piece['right_ns'])-piece['left_ns'])
        if span:result+=span*response_rate(piece['state'],beta)
    return result


def rate_table(beta):
    return {(phase,count,same):response_rate(dict(peer_visible_macro_owner_count=count,
        peer_same_visible_macro_phase_owner_count=same),beta)
        for phase in ('entry','prefill','decode','ready_tail','ocr_inference')
        for count in range(4) for same in range(count+1)}


def request_vector(request,row,beta,fit):
    """Compile occurrence-origin coordinates; strip absolute stamps and IDs."""
    start=row['observed_worker_start_time_ns'];submitted=row['actual_submit_time_ns']
    require(type(start) is int and type(submitted) is int and 0<=submitted<=start
        and row['worker_response']['start_perf_ns']==start
        and row['previous_handler_next_request_ready']['clock']=='host_perf_counter_ns',
        'Submit/worker START and READY host-perf clock contract required')
    nodes=[];macro_sources=[];query_evidence=[]
    for macro_index,macro in enumerate(request['macros']):
        left,right=macro['left_ns'],macro['right_ns'];work=progress(macro,right,beta)
        marks=[]
        for milestone in macro['internal_training_milestones']:
            e=milestone['raw_event'];edge=e.get('event');segment=e.get('segment_id')
            query=e.get('kind')=='device_event_query'
            if query:
                require(e.get('evidence_scope')=='recorded_current_stream_only'
                    and type(e.get('end_event_complete')) is bool
                    and all(k in e for k in ('event_id','phase_id','stream_id','device_index',
                        'host_query_begin_ns','host_query_end_ns')),
                    'Complete source query identity/bracket and explicit current-stream scope required')
                query_evidence.append(dict(raw_event_pointer=milestone['raw_event_pointer'],raw_event=dict(e)))
            if query:action='query'
            elif edge=='start' and segment in ('native_inference','native_ocr'):action='phase'
            elif edge=='start' and e.get('semantic_phase') in ('prefill','decode'):action='phase'
            elif edge=='end' and segment in ('native_inference','native_ocr'):action='clear'
            else:action='diagnostic'
            phase=('entry' if segment=='native_inference' else 'ocr_inference' if segment=='native_ocr'
                else e.get('semantic_phase')) if action=='phase' else None
            marks.append(dict(identity='event:'+str(milestone['raw_event_ordinal']),
                reference_work_at=fraction_record(progress(macro,e['perf_ns'],beta)),
                **lags(e['perf_ns'],e['received_time_ns'],e['collector_dequeued_time_ns'],e['collector_processing_time_ns']),
                action=action,phase=phase,
                source_macro_id=e.get('phase_id',segment),occurrence_macro_id=macro['macro_id'],
                query_complete=e.get('end_event_complete') if query else None,
                query_scope=e.get('evidence_scope') if query else None,
                event_reference_phase_id=e.get('phase_id') if query else None,
                physical_SM_service_ns=None,all_request_GPU_work_complete=None,
                clear_scope='request' if action=='clear' else None))
        result_at=row['worker_response']['end_perf_ns']
        if left<=result_at<right or (macro_index==len(request['macros'])-1 and result_at==right):
            marks.append(dict(identity='RESULT',reference_work_at=fraction_record(progress(macro,result_at,beta)),
                **lags(result_at,row['response_reader_event_enqueue_time_ns'],
                    row['response_collector_dequeued_time_ns'],row['response_collector_processing_time_ns']),
                action='result',phase=None,source_macro_id=macro['macro_id'],occurrence_macro_id=macro['macro_id'],
                query_complete=None,query_scope=None,event_reference_phase_id=None,clear_scope=None))
        marks.sort(key=lambda m:fraction_read(m['reference_work_at']))
        shape=macro['forward_shape'] or {}
        group=[macro['owner'],macro['pool_id'],macro['task'],macro['macro_id'],macro['semantic_phase'],macro['kind'],
            *(shape.get(k) for k in ('input_sequence_length','input_batch_size','forward_index'))]
        baseline=next((x for x in fit['baselines'] if x['group']==group),None)
        require(baseline is not None,'Exact public input/macro shape fitted nuisance support required')
        nodes.append(dict(macro_id=macro['macro_id'],phase=macro['semantic_phase'],kind=macro['kind'],
            reference_work_ns=fraction_record(work),marks=marks,
            baseline_reference_ms=math.exp(baseline['log_reference_ms']),
            log_reference_work_residual=math.log(float(work)/1e6)-baseline['log_reference_ms']))
        macro_sources.append(dict(macro_id=macro['macro_id'],raw_interval=[left,right]))
    ready=row['previous_handler_next_request_ready'];at=ready['perf_ns']
    vector=dict(public_key=[row['model'],row['task'],row['pool_id']],nodes=nodes,
        ready_lags=lags(at,ready['received_time_ns'],ready['collector_dequeued_time_ns'],ready['collector_processing_time_ns']),
        dispatch_to_worker_start_ns=start-submitted,
        observed_submit_to_START_may_include_worker_pipe_FIFO_wait=True,
        pure_idle_handoff_qualified=False,
        all_entry_forward_OCR_and_READY_tail_retained=True,
        future_shapes_and_generation_stop_are_training_template_only=True)
    vector['vector_id']=hashlib.sha256(json.dumps(vector,sort_keys=True).encode()).hexdigest()
    return vector,dict(request_id=row['request_id'],macro_intervals=macro_sources,
        original_query_identity_evidence=query_evidence,
        symbolic_runtime_stream_mapping_is_physical_authentication=False)


def build_law(documents,fit):
    require(fit.get('second_order_qualification') is True,'Numerically qualified training response equation required')
    beta=fit['coefficients'];require(len(beta)==2,'Explicit phase-aware response coefficients required')
    from .composable_response_macros_v1 import extract,SCHEMA as MACRO_SCHEMA
    captures={m['capture_sha256'] for d in documents for r in d['requests'] for m in r['macros']}
    require(bool(documents) and len(captures)==len(documents)
        and captures==set(fit['captures']) and fit.get('candidate')=='visible_phase_aware',
        'Distinct complete training captures must exactly match the response fit')
    vectors=[];provenance=[];execution_sets=[]
    for doc in documents:
        require(doc.get('schema')==MACRO_SCHEMA and doc.get('mode')=='natural'
            and doc.get('validation_labels_read') is False
            and all(m.get('response_domain')=='natural_forward_and_async_tail_wall'
                and m.get('true_SM_service_identified') is False for r in doc['requests'] for m in r['macros']),
            'Natural host response clocks required; cross-domain transfer is unqualified')
        for source in doc['sources']:require(local.receipt(source['path'])==source,'Changed macro source')
        require(extract(doc['sources'][0]['path'])==doc,'Modified macro labels must rederive exactly')
        review=local.checked(doc['sources'][0]);raw_ref=review['inputs']['raw.json'];raw=local.checked(raw_ref)
        context=local.checked(review['inputs']['context.json'])
        execution_sets.append(sorted({s['frozen']['sha256'] for s in context['execution_sources']}))
        rows={r['request_id']:r for r in raw['request_records']}
        for request in doc['requests']:
            vector,source=request_vector(request,rows[request['request_id']],beta,fit)
            # Capture is a common latent block/provenance, never a lookup by cohort.
            vector['training_capture_sha256']=raw_ref['sha256'];vectors.append(vector)
            provenance.append(dict(vector_id=vector['vector_id'],capture_sha256=raw_ref['sha256'],**source))
    require(all(s==execution_sets[0] for s in execution_sets),'Training execution identities differ')
    return dict(schema=SCHEMA,status='EMPIRICAL_JOINT_REQUEST_VECTOR_RESPONSE_TRANSPORT_CANDIDATE_ONLY',
        beta=beta,rate_rational_denominator=RATE_DENOMINATOR,vectors=vectors,
        provenance_not_used_for_lookup=provenance,captures=sorted({v['training_capture_sha256'] for v in vectors}),
        exact_public_content_conditioned=True,complete_request_residual_vector_preserved=True,
        equal_capture_weighting=True,common_capture_latent_across_public_inputs=True,
        within_capture_request_draws_independent_given_capture_assumption=True,
        marked_virtual_clock_transport_is_new_assumption=True,
        paired_notice_delay_residuals_transport_unchanged_is_new_assumption=True,
        dynamic_peer_paths_generated_by_reference_not_replayed=True,
        prospective_generation_template_qualified=False,notification_loss_model_qualified=False,
        producer_fifo_composition_conflicts_must_return_UNKNOWN=True,
        main_queue_provider_eligible=False,native_assimilation_eligible=False,
        validation_labels_read=False,GPU_started=False)


def verified_inputs(paths,fit_path):
    from .macro_joint_response_fit_v1 import verified_document
    fit_ref=local.receipt(fit_path);report=local.checked(fit_ref)
    require(report.get('schema')=='gsdeploy.macro_joint_response_second_order_training_leaveout.v1'
        and report.get('validation_labels_read') is False
        and report.get('numerical_solver_uses_heldout_labels') is False,
        'Second-order three-training-capture response report required')
    for source in report['sources']:
        require(local.receipt(source['path'])==source,'Changed response fit closure')
    candidate=next(c for c in report['candidates'] if c['candidate']==report['selected_candidate'])
    require(candidate['candidate']=='visible_phase_aware'
        and candidate['full_fit_and_all_folds_numerically_qualified'] is True,
        'Full response fit and all folds must be numerically qualified')
    documents=[];sources=[fit_ref,*report['sources']]
    for path in paths:
        document,closure=verified_document(path);documents.append(document);sources.extend(closure)
    captures={r['capture_sha256'] for doc in documents for r in doc['requests'] for r in r['macros']}
    require(len(documents)==len(captures)==3 and captures==set(candidate['captures']),
        'Exactly matched three distinct response-fit training captures required')
    return documents,candidate,list({r['path']:r for r in sources}.values())


def choose_vector(law,public_key,*,capture_quantile,within_capture_quantile):
    require(type(public_key) in (tuple,list) and len(public_key)==3,'Public owner/task/exact-input key required')
    for q in (capture_quantile,within_capture_quantile):
        require(type(q) in (int,float) and math.isfinite(q) and 0<=q<1,'Explicit finite quantile in [0,1) required')
    captures=law['captures'];require(bool(captures),'Training capture support required')
    capture=captures[min(len(captures)-1,int(capture_quantile*len(captures)))]
    vectors=[v for v in law['vectors'] if v['training_capture_sha256']==capture and v['public_key']==list(public_key)]
    if not vectors:return dict(status='UNKNOWN_EXACT_PUBLIC_INPUT_IN_SELECTED_CAPTURE')
    vector=copy.deepcopy(vectors[min(len(vectors)-1,int(within_capture_quantile*len(vectors)))])
    return dict(status='TRAINING_JOINT_REQUEST_VECTOR_DRAW_ONLY',vector=vector,
        common_training_capture_latent=capture,main_queue_provider_eligible=False)


def to_reference_plan(vector,*,public_dispatch_ordinal):
    require(type(public_dispatch_ordinal) is int and public_dispatch_ordinal>=0,'Public dispatch ordinal required')
    handoff=vector.get('dispatch_to_worker_start_ns')
    require(type(handoff) is int and handoff>=0,'Explicit nonnegative integer dispatch-to-START lag required')
    ready=checked_lags(vector.get('ready_lags'))
    owner=vector['public_key'][0];producer=owner+':modeled_stdout_lifetime';macros=[]
    for node in vector['nodes']:
        marks=[]
        for mark in node['marks']:
            keys={'reader_delay_ns','dequeue_extra_ns','processing_extra_ns'}
            require(keys<=set(mark),'All notification delay legs required')
            delay=sum(checked_lags({k:mark[k] for k in keys}).values())
            marks.append(Mark(identity=mark['identity'],work_ns=fraction_read(mark['reference_work_at']),
                processing_delay_ns=Fraction(delay),action=mark['action'],producer_id=producer,phase=mark['phase'],
                reader_delay_ns=Fraction(mark['reader_delay_ns']),
                event_id=(owner+':draw:'+str(public_dispatch_ordinal)+':'+mark['event_reference_phase_id']+':stream_end')
                    if mark['action']=='query' else None,
                stream_id=owner+':symbolic_recorded_current_stream' if mark['action']=='query' else None,
                query_complete=mark['query_complete'],clear_scope=mark['clear_scope']))
        macros.append(Macro(node['macro_id'],node['phase'],fraction_read(node['reference_work_ns']),tuple(marks)))
    plan=RequestPlan(tuple(macros),Fraction(sum(ready.values())),producer,
        dispatch_to_worker_start_ns=Fraction(handoff),ready_reader_delay_ns=Fraction(ready['reader_delay_ns']))
    validate_plan(plan);return plan
